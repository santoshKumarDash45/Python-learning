# Assignment Operator - demonstrates simple and compound assignment operators in Python

x = 10          # assign integer value 10 to variable x
x += 20         # compound assignment: x = x + 20, so x becomes 30
print(x)        # prints 30

# here answer is 30 because x+=20 means x = x+20 and x is 10 so 10+20 is equal to 30
# here x=10 is called as simple assignment operator and x+=20 is called as compound assignment operator 
# when with any simple assignment operator another operator is combined then it is called as compound assignment operator



y = 10          # assign integer value 10 to variable y
y &= 5          # compound bitwise AND assignment: y = y & 5, binary 1010 & 0101 = 0000, so y becomes 0
print(y)        # prints 0

