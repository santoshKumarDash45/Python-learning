x=10
x+=20
print(x) 

# here answer is 30 because x+=20 means x = x+20 and x is 10 so 10+20 is equal to 30
# here x=10 is called as simple assignment operator and x+=20 is called as compound assignment operator 
# when with any simple assignment operator another operator is combined then it is called as compound assignment operator



